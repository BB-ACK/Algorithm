WITH FRONT_END AS (
    SELECT SUM(CODE) AS CODE
    FROM SKILLCODES
    WHERE CATEGORY = 'Front End'
)
SELECT *
FROM (SELECT CASE
        WHEN (D.SKILL_CODE & F.CODE) != 0 AND (D.SKILL_CODE & P.CODE) != 0 THEN 'A'
        WHEN (D.SKILL_CODE & C.CODE) != 0 THEN 'B'
        WHEN (D.SKILL_CODE & F.CODE) != 0 THEN 'C'
        END AS GRADE, ID, EMAIL
        FROM DEVELOPERS D, FRONT_END F, (SELECT CODE FROM SKILLCODES WHERE NAME = 'Python') P, (SELECT CODE FROM SKILLCODES WHERE NAME = 'C#') C) AS T
WHERE T.GRADE IS NOT NULL
ORDER BY T.GRADE ASC, T.ID ASC