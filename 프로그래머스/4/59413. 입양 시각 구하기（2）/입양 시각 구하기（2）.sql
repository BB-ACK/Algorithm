WITH RECURSIVE HOURS AS (
    SELECT 0 AS HOUR
    UNION ALL
    SELECT HOUR + 1
    FROM HOURS
    WHERE HOUR < 23
)
SELECT HOUR, COALESCE(COUNT, 0) AS COUNT
FROM HOURS H LEFT JOIN (SELECT EXTRACT(HOUR FROM DATETIME) AS HOUR, COUNT(*) AS COUNT
                      FROM ANIMAL_OUTS
                      GROUP BY EXTRACT(HOUR FROM DATETIME)
                      ORDER BY HOUR) R USING(HOUR)