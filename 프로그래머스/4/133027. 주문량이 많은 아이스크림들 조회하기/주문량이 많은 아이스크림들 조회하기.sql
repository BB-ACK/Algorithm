WITH TOTAL AS (
    SELECT FLAVOR, SUM(TOTAL_ORDER + ORDERS) AS TOTAL_ORDER
    FROM FIRST_HALF JOIN (SELECT FLAVOR, SUM(TOTAL_ORDER) AS ORDERS
                          FROM JULY
                          GROUP BY FLAVOR) USING(FLAVOR)
    GROUP BY FLAVOR
    ORDER BY TOTAL_ORDER DESC
)
SELECT FLAVOR
FROM TOTAL
OFFSET 0 ROW FETCH NEXT 3 ROWS ONLY