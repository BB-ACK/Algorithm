WITH RANKED AS (
    SELECT MEMBER_ID, COUNT(*), ROW_NUMBER() OVER(ORDER BY COUNT(*) DESC) AS RANK
    FROM REST_REVIEW
    GROUP BY MEMBER_ID
)
SELECT MEMBER_NAME, REVIEW_TEXT, TO_CHAR(REVIEW_DATE, 'YYYY-MM-DD') AS REVIEW_DATE
FROM MEMBER_PROFILE JOIN REST_REVIEW USING(MEMBER_ID)
WHERE MEMBER_ID IN (SELECT MEMBER_ID
                    FROM RANKED
                    WHERE RANK = 1)
ORDER BY REVIEW_DATE ASC, REVIEW_TEXT ASC