SELECT YEAR, MONTH, GENDER, COUNT(*) AS USERS
FROM USER_INFO JOIN (SELECT EXTRACT(YEAR FROM SALES_DATE) AS YEAR, 
                    EXTRACT(MONTH FROM SALES_DATE) AS MONTH, USER_ID
                    FROM ONLINE_SALE
                    GROUP BY EXTRACT(YEAR FROM SALES_DATE), EXTRACT(MONTH FROM SALES_DATE), USER_ID)
                    USING (USER_ID)
WHERE GENDER IS NOT NULL
GROUP BY YEAR, MONTH, GENDER
ORDER BY YEAR ASC, MONTH ASC, GENDER ASC
