WITH AVAILABLE_CAR AS (
    SELECT *
    FROM CAR_RENTAL_COMPANY_CAR
    WHERE CAR_ID NOT IN (SELECT DISTINCT CAR_ID
                     FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
                     WHERE START_DATE <= TO_DATE('2022-11-30', 'YYYY-MM-DD') 
                     AND END_DATE >= TO_DATE('2022-11-01', 'YYYY-MM-DD')) AND CAR_TYPE IN ('SUV', '세단')
    ORDER BY CAR_ID
)
SELECT CAR_ID, CAR_TYPE, (DAILY_FEE * (1 - DISCOUNT_RATE/100)) * 30 AS FEE
FROM CAR_RENTAL_COMPANY_DISCOUNT_PLAN JOIN AVAILABLE_CAR USING(CAR_TYPE)
WHERE DURATION_TYPE LIKE '%30%' AND (DAILY_FEE * (1 - DISCOUNT_RATE/100)) * 30 >= 500000 AND (DAILY_FEE * (1 - DISCOUNT_RATE/100)) * 30 < 2000000
ORDER BY FEE DESC, CAR_TYPE ASC, CAR_ID ASC
